package dev.jasagent.agentpass.server;

/**
 * 通行证流水的四种事件。领证、核销、拒绝和重放各记一条，不记录登录令牌或证明文。
 */
public enum AuditKind {
    /**
     * 已登录用户通过策略检查，服务发出了一张尚未使用的一次性证。
     */
    ISSUE,

    /**
     * 校验通过后的第一次核销，证从这时起不能再进入业务。
     */
    REDEEM,

    /**
     * 拒绝发证，或核销时发现证明无效、过期、用户或目标不匹配。
     */
    DENY,

    /**
     * 一张已经核销过的证再次被拿来核销。
     */
    REPLAY
}
