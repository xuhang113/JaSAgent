package dev.jasagent.api.exception;

/**
 * {@link AgentException} 携带的错误分类。
 * 调用方用它区分模型、工具、权限、持久化和工作流等失败。
 */
public enum ErrorCode {
    /**
     * 模型没有配置、路由失败，或供应商调用失败。
     */
    LLM,
    /**
     * 工具参数不合法，或工具执行失败。
     */
    TOOL,
    /**
     * 插件缺失、标识重复、统计实现份数不对，或插件按失败策略中止了调用。
     */
    PLUGIN,
    /**
     * MCP 握手、列工具、远端调用失败，或两个服务器登记出了同一个工具名。
     */
    MCP,
    /**
     * 检索没有完成。索引读不到、召回失败或结果交不回去时使用这个分类。
     */
    RAG,
    /**
     * 工作流定义不合法，或执行无法按图继续。
     */
    WORKFLOW,
    /**
     * 执行库或检查点存储器打不开、写不进或读不到。
     */
    PERSIST,
    /**
     * 调用方无权操作这条执行、会话或目录。
     */
    AUTH,
    /**
     * 执行在运行过程中被打断。
     */
    INTERRUPTED,
    /**
     * 执行被取消，后面的步骤不再继续。
     */
    CANCELLED,
    /**
     * 没有更具体分类的内部失败。异步边界收到空结果时也用它。
     */
    INTERNAL,
    /**
     * 推理节点的模型请求次数达到该节点写下的上限。
     */
    WORKFLOW_MAX_STEPS
}
